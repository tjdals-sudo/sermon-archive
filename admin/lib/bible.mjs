// 이름이 긴 것부터 먼저 찾아야 "요한복음"이 "요한"으로 잘리지 않습니다.
const NAMES = BOOKS.flatMap(([full, code, abbr]) => [[full, code, full], [abbr, code, full]])
  .sort((a, b) => b[0].length - a[0].length);

const PATTERN = new RegExp(
  `(${NAMES.map((n) => n[0]).join('|')})\\s*(\\d{1,3})\\s*[:장편]\\s*(\\d{1,3})(?:\\s*절?\\s*[-~]\\s*(\\d{1,3}))?`,
);

/** 본문 구절을 찾아 { ref, url } 로 돌려줍니다. 못 찾으면 null */
export function findScripture(text) {
  const m = PATTERN.exec(text);
  if (!m) return null;
  const [, name, chap, from, to] = m;
  const entry = NAMES.find((n) => n[0] === name);
  const ref = `${entry[2]} ${chap}:${from}${to ? `-${to}` : ''}`;
  return { ref, url: bibleUrl(entry[1], chap) };
}

/**
 * 성경 사이트 링크.
 * 다른 사이트를 쓰고 싶으면 이 함수 한 줄만 바꾸면 됩니다.
 *  - 지금: YouVersion 한국어 개역개정
 */
export function bibleUrl(code, chapter) {
  return `https://www.bible.com/ko/bible/88/${code}.${chapter}`;
}

/** "요한복음 3:16" 같은 사람이 쓴 문자열로도 링크를 만듭니다 */
export function urlFromRef(ref) {
  const found = findScripture(String(ref || ''));
  return found ? found.url : '';
}
